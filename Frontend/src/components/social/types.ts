// Shapes of the Social Hub API's answers (Backend/Doc/SocialHub.md)

export type Role = 'admin' | 'team_leader' | 'team_member' | 'user'
export type Visibility = 'public' | 'team' | 'connections'
export type ModerationStatus = 'clean' | 'flagged' | 'hidden' | 'removed'
export type ApprovalStatus = 'none' | 'pending' | 'approved' | 'rejected'
export type PublishStatus = 'none' | 'published' | 'failed'
export type Provider = 'linkedin' | 'github'
export type ExternalTarget = Provider
export type PersonalTaskStatus = 'todo' | 'in_progress' | 'completed'
export type Priority = 'low' | 'medium' | 'high'
export type JobStatus = 'queued' | 'processing' | 'completed' | 'failed'

export type Person = {
  _id: string
  name: string
  email?: string
  role?: Role | string
  profileImage?: string | null
  department?: string | null
  teamId?: string | null
}

export type Comment = {
  _id: string
  text: string
  createdAt?: string
  user: Person | string | null
}

export type PublishResult = {
  status: PublishStatus
  message?: string | null
  externalId?: string | null
  publishedAt?: string | null
  publishingAt?: string | null
}

export type PostViewer = {
  canApprove: boolean
  canPublish: boolean
  canEdit: boolean
  canDelete: boolean
}

export type Targets = { pandav: boolean; linkedin: boolean; github: boolean }

// An uploaded image; its bytes are at socialImageUrl(_id)
export type PostImage = {
  _id: string
  type: string
  width: number
  height: number
  altText?: string
  size?: number
}

// A publish job a post still has to run, by provider
export type QueuedJob = {
  _id: string
  status: 'queued' | 'processing'
  attempts: number
  maxAttempts: number
  nextRetryAt?: string | null
  lastError?: string | null
}

export type SocialPost = {
  _id: string
  title?: string | null
  content: string
  tags?: string[]
  mediaUrls?: string[]
  images?: PostImage[]
  visibility: Visibility
  moderationStatus: ModerationStatus
  moderationReason?: string | null
  moderatedBy?: Person | string | null
  moderatedAt?: string | null
  approvalStatus: ApprovalStatus
  approvedAt?: string | null
  editedAt?: string | null
  createdAt: string
  likes: string[]
  comments: Comment[]
  author: Person | null
  sourceTask?: { _id: string; title: string; status: string; completedAt?: string | null } | null
  targets: Targets
  publishResults?: Partial<Record<'pandav' | Provider, PublishResult>>
  // Goes to LinkedIn by itself: at publishAt, or as soon as it may
  autoPublish?: boolean
  publishAt?: string | null
  queuedJobs?: Partial<Record<Provider, QueuedJob>>
  viewer?: PostViewer
}

export type FeedCursor = { before: string; beforeId: string }

export type PersonalTask = {
  _id: string
  title: string
  description?: string
  priority: Priority
  status: PersonalTaskStatus
  dueDate?: string | null
  completedAt?: string | null
  autoGenerateLinkedInPost: boolean
  lastAutoGeneratedPost?: string | null
  autoPostStatus?: 'none' | 'pending_approval' | 'approved' | 'rejected' | 'published' | 'failed' | 'already_generated'
  autoPostMessage?: string | null
  createdAt?: string
}

export type AutoShare =
  | { skipped: true; reason: string; postId?: string }
  | { suggested: true; draft: { title: string; content: string } }
  | null

export type Connection = {
  _id: string
  status: 'pending' | 'accepted' | 'rejected'
  requester: Person | string
  recipient: Person | string
  respondedAt?: string | null
  createdAt?: string
}

export type ConnectionState = {
  pendingSent: Connection[]
  pendingReceived: Connection[]
  connected: Connection[]
}

export type Integration = {
  _id: string
  provider: Provider
  accountHandle: string
  isConnected: boolean
  needsRelink?: boolean
  scopes?: string[]
  tokenExpiresAt?: string | null
  accessTokenHint?: string
  connectedAt?: string
  metadata?: {
    name?: string
    avatarUrl?: string
    profileUrl?: string
    picture?: string
    email?: string
    localizedFirstName?: string
    localizedLastName?: string
  } | null
}

export type PublishJob = {
  _id: string
  provider: Provider
  status: JobStatus
  attempts: number
  maxAttempts: number
  nextRetryAt?: string | null
  startedAt?: string | null
  completedAt?: string | null
  lastError?: string | null
  owner?: Person | string | null
  queuedBy?: Person | string | null
  payload?: { githubRepo?: string | null } | null
  result?: { externalId?: string | null; alreadyPublished?: boolean } | null
  createdAt?: string
  post?: {
    _id?: string
    title?: string | null
    content?: string
    approvalStatus?: ApprovalStatus
    targets?: Targets
  } | string | null
}

export type ReportedMessage = {
  _id: string
  kind: 'direct' | 'team'
  sender: { _id: string; name: string } | null
  receiver: { _id: string; name: string } | null
  team: { _id: string; name: string } | null
  text: string
  sentAt: string
  isEdited?: boolean
  deletedAt?: string | null
  reportCount: number
  lastReportedAt: string
  reports: Array<{ by: { _id: string; name: string } | null; reason?: string; text?: string; at: string }>
}
